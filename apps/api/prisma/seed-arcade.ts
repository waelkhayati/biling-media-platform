const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString: url }) });
async function main() {
  const data = samples.map((sample) => {
    const puzzle = arcadePuzzleInputSchema.parse({ ...sample, date, published: true });
    return { ...puzzle, kind: puzzle.definition.kind };
  });
  const result = await prisma.arcadePuzzle.createMany({ data, skipDuplicates: true });
  console.log("Added " + result.count + " local arcade puzzles for " + date + " UTC.");
}
main()
  .catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : "Arcade seed failed.");
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
